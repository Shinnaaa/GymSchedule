export const MESSAGES = { en, zh, ja };

export function translate(lang, key, vars = {}) {
  const text = (MESSAGES[lang] || en)[key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}

/** Defaults for a new user's state, in their language. */
export function localizedDefaults(lang) {
  const t = (k) => translate(lang, k);
  return {
    planLabels: { push: t("plan.push"), pull: t("plan.pull"), legs: t("plan.legs"), cardio: t("plan.cardio") },
    mobility: [t("mob.1"), t("mob.2"), t("mob.3"), t("mob.4")],
  };
}
